const dicts = { en, zh }

function currentLanguage(): Language {
  const language =
    typeof localStorage !== "undefined" ? localStorage.getItem("language") : null
  return language === "zh" || language === "en" ? language : "en"
}

export function useI18n() {
  const [language, setLangState] = useState<Language>(currentLanguage)
  useEffect(() => {
    const onChange = () => setLangState(currentLanguage())
    window.addEventListener(LANG_EVENT, onChange)
    return () => window.removeEventListener(LANG_EVENT, onChange)
  }, [])
  return {
    language,
    setLanguage: (lang: Language) => {
      localStorage.setItem("language", lang)
      window.dispatchEvent(new Event(LANG_EVENT))
    },
  }
}

export function t(
  key: string,
  fallback?: string,
  vars?: Record<string, string | number>,
): string {
  const lang = currentLanguage()
  const parts = key.split(".")
  let value: unknown = dicts[lang]
  for (const part of parts) {
    if (value && typeof value === "object" && part in value) {
      value = (value as Record<string, unknown>)[part]
    } else {
      value = undefined
      break
    }
  }
  let out =
    typeof value === "string"
      ? value
      : fallback && fallback !== "zh" && fallback !== "en"
        ? fallback
        : key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return out
}
